IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tiff", ".tif", ".hdr", ".exr"}


def is_power_of_two(n: int) -> bool:
    return (n > 0) and (n & (n - 1)) == 0


def classify_image(img: Image.Image, filename: str) -> str:
    """Classify 3D web role based on aspect ratio, channels, and metadata."""
    w, h = img.size
    aspect = w / h

    # 360 Panorama / HDRI environment
    if 1.9 <= aspect <= 2.1 or filename.lower().endswith((".hdr", ".exr")):
        return "environment_ibl"

    # Has alpha transparency
    if img.mode in ("RGBA", "LA") or (img.mode == "P" and "transparency" in img.info):
        return "billboard_cutout"

    # Square or close to square: ideal surface texture
    if 0.85 <= aspect <= 1.15:
        return "texture_surface"

    # Default to general object or surface
    return "object_or_prop"


def inspect_folder(folder_path: Path) -> list[dict]:
    """Scan folder and return technical analysis for each image."""
    results = []
    if not folder_path.exists():
        print(f"[ERROR] Folder not found: {folder_path}", file=sys.stderr)
        return results

    for file in sorted(folder_path.iterdir()):
        if file.suffix.lower() in IMAGE_EXTENSIONS:
            try:
                with Image.open(file) as img:
                    w, h = img.size
                    role = classify_image(img, file.name)
                    pot_w = is_power_of_two(w)
                    pot_h = is_power_of_two(h)
                    rec_size = (get_nearest_pot(w), get_nearest_pot(h))

                    results.append({
                        "filename": file.name,
                        "path": str(file.resolve()),
                        "size_bytes": file.stat().st_size,
                        "size_kb": round(file.stat().st_size / 1024, 1),
                        "width": w,
                        "height": h,
                        "aspect_ratio": round(w / h, 2),
                        "channels": img.mode,
                        "is_pot": pot_w and pot_h,
                        "recommended_pot": rec_size,
                        "detected_role": role,
                    })
            except Exception as e:
                results.append({
                    "filename": file.name,
                    "path": str(file.resolve()),
                    "error": str(e)
                })
    return results


def generate_threejs_code(assets: list[dict], relative_asset_path: str = "./textures/") -> str:
    """Generate ready-to-paste Three.js and WebGPU material setup code."""
    code_lines = [
        "// ==========================================================================",
        "// Three.js / WebGPU PBR Material Definitions (Generated by image-to-3d-web)",
        "// ==========================================================================",
        "import * as THREE from 'three';",
        "// For WebGPU TSL projects, you can alternatively use:",
        "// import { MeshPhysicalNodeMaterial, texture } from 'three/webgpu';",
        "",
        "const textureLoader = new THREE.TextureLoader();",
        "",
        "// Helper to configure realistic PBR texture wrapping and color spaces",
        "function setupPBRTexture(tex, isSRGB = false, repeatX = 1, repeatY = 1) {",
        "  tex.wrapS = THREE.RepeatWrapping;",
        "  tex.wrapT = THREE.RepeatWrapping;",
        "  tex.repeat.set(repeatX, repeatY);",
        "  tex.colorSpace = isSRGB ? THREE.SRGBColorSpace : THREE.NoColorSpace;",
        "  return tex;",
        "}",
        "",
        "export const materials = {};",
        ""
    ]

    for asset in assets:
        if asset.get("error"):
            continue
        stem = Path(asset["filename"]).stem
        var_name = stem.replace("-", "_").replace(" ", "_").lower() + "Material"
        base_dir = relative_asset_path.rstrip("/") + "/"

        code_lines.extend([
            f"// --- Material for {asset['filename']} ({asset['detected_role']}) ---",
            f"materials.{var_name} = new THREE.MeshPhysicalMaterial({{",
            f"  map: setupPBRTexture(textureLoader.load('{base_dir}{stem}_diffuse.webp'), true),",
            f"  normalMap: setupPBRTexture(textureLoader.load('{base_dir}{stem}_normal.png'), false),",
            f"  normalScale: new THREE.Vector2(1.0, 1.0),",
            f"  roughnessMap: setupPBRTexture(textureLoader.load('{base_dir}{stem}_roughness.png'), false),",
            f"  roughness: 0.85,",
            f"  aoMap: setupPBRTexture(textureLoader.load('{base_dir}{stem}_ao.png'), false),",
            f"  aoMapIntensity: 1.0,",
            f"  metalness: 0.05,",
            f"  clearcoat: 0.1,",
            f"  clearcoatRoughness: 0.1,",
            f"}});",
            ""
        ])

    return "\n".join(code_lines)


def process_image(
    file_path: Path,
    out_dir: Path,
    pot: bool = True,
    pot_size: int = 1024,
    seamless: bool = False,
    normal_strength: float = 2.0,
    export_webp: bool = True
) -> dict:
    """Process a single image and generate full PBR texture set."""
    stem = file_path.stem
    out_dir.mkdir(parents=True, exist_ok=True)

    with Image.open(file_path) as raw_img:
        # Convert to RGB if palette or CMYK
        if raw_img.mode in ("P", "CMYK"):
            img = raw_img.convert("RGBA" if "transparency" in raw_img.info else "RGB")
        else:
            img = raw_img.copy()

        # 1. POT Resize if requested
        if pot:
            img = resize_to_pot(img, target_size=(pot_size, pot_size))

        # 2. Seamless blend if requested
        if seamless:
            img = make_seamless(img)

        # Save diffuse/albedo
        diffuse_png = out_dir / f"{stem}_diffuse.png"
        img.save(diffuse_png, "PNG")

        if export_webp:
            diffuse_webp = out_dir / f"{stem}_diffuse.webp"
            img.save(diffuse_webp, "WEBP", quality=92)

        # 3. Generate Normal Map (OpenGL +Y standard for Three.js)
        normal_map = generate_normal_map(img, strength=normal_strength)
        normal_path = out_dir / f"{stem}_normal.png"
        normal_map.save(normal_path, "PNG")

        # 4. Generate Roughness Map
        rough_map = generate_roughness_map(img, contrast=1.3)
        rough_path = out_dir / f"{stem}_roughness.png"
        rough_map.save(rough_path, "PNG")

        # 5. Generate Ambient Occlusion (AO) Map
        ao_map = generate_ao_map(img, intensity=1.2)
        ao_path = out_dir / f"{stem}_ao.png"
        ao_map.save(ao_path, "PNG")

        # 6. Generate Displacement / Height Map
        disp_map = generate_displacement_map(img)
        disp_path = out_dir / f"{stem}_displacement.png"
        disp_map.save(disp_path, "PNG")

        return {
            "source": file_path.name,
            "diffuse": str(diffuse_png.name),
            "normal": str(normal_path.name),
            "roughness": str(rough_path.name),
            "ao": str(ao_path.name),
            "displacement": str(disp_path.name),
            "resolution": f"{img.size[0]}x{img.size[1]}",
        }


def main():
    parser = argparse.ArgumentParser(
        description="Inspect and develop photos in a directory into 3D Web & PBR ready assets."
    )
    parser.add_argument("folder", type=str, help="Path to folder containing photos/images")
    parser.add_argument(
        "--action",
        type=str,
        choices=["inspect", "pbr", "pot", "seamless", "code", "all"],
        default="inspect",
        help="Action to perform: inspect, pbr, pot, seamless, code, or all (default: inspect)"
    )
    parser.add_argument("--output-dir", type=str, default=None, help="Output directory for developed assets")
    parser.add_argument("--pot-size", type=int, default=1024, help="Target POT size: 512, 1024, 2048 (default: 1024)")
    parser.add_argument("--strength", type=float, default=2.0, help="Normal map bump strength (default: 2.0)")
    parser.add_argument("--seamless", action="store_true", help="Force seamless edge blending for repeating textures")
    parser.add_argument("--json", action="store_true", help="Output results in JSON format")

    args = parser.parse_args()
    folder_path = Path(args.folder).resolve()

    if not folder_path.exists() or not folder_path.is_dir():
        print(f"[ERROR] Directory does not exist: {folder_path}", file=sys.stderr)
        sys.exit(1)

    inspected = inspect_folder(folder_path)

    if not inspected:
        print(f"No supported image files found in {folder_path}")
        sys.exit(0)

    if args.action == "inspect":
        if args.json:
            print(json.dumps(inspected, indent=2))
        else:
            print("\n" + "=" * 80)
            print(f"📸 Image 3D Web Inspection Report: {folder_path.name}")
            print("=" * 80)
            print(f"{'Filename':<28} | {'Dims':<11} | {'POT?':<5} | {'Role':<18} | {'Rec POT':<10}")
            print("-" * 80)
            for item in inspected:
                if item.get("error"):
                    print(f"{item['filename']:<28} | [ERROR] {item['error']}")
                    continue
                dims = f"{item['width']}x{item['height']}"
                pot_str = "YES" if item['is_pot'] else "NO"
                rec_pot = f"{item['recommended_pot'][0]}x{item['recommended_pot'][1]}"
                print(f"{item['filename'][:27]:<28} | {dims:<11} | {pot_str:<5} | {item['detected_role']:<18} | {rec_pot:<10}")
            print("-" * 80)
            print(f"Total scanned: {len(inspected)} image(s).")
            print("To develop full PBR suites (Normal, Roughness, AO), run with: --action all or --action pbr\n")

    elif args.action in ("pbr", "pot", "seamless", "all"):
        out_dir = Path(args.output_dir).resolve() if args.output_dir else folder_path / "developed_3d_assets"
        print(f"🚀 Developing {len(inspected)} image(s) to 3D Web PBR assets...")
        print(f"📂 Output target: {out_dir}\n")

        developed = []
        for item in inspected:
            if item.get("error"):
                continue
            src_file = Path(item["path"])
            print(f"  ⚡ Processing: {src_file.name} (Role: {item['detected_role']})")
            res = process_image(
                src_file,
                out_dir,
                pot=(args.action in ("pot", "all", "pbr")),
                pot_size=args.pot_size,
                seamless=args.seamless or (args.action == "seamless"),
                normal_strength=args.strength,
                export_webp=True
            )
            developed.append(res)

        # Generate Three.js material code
        three_code = generate_threejs_code(inspected)
        code_file = out_dir / "threejs_materials.js"
        code_file.write_text(three_code, encoding="utf-8")

        manifest_file = out_dir / "asset_manifest.json"
        manifest_file.write_text(json.dumps(developed, indent=2), encoding="utf-8")

        print(f"\n✅ All assets developed successfully!")
        print(f"  - PBR Maps generated: Normal (+Y OpenGL), Roughness, AO, Displacement")
        print(f"  - POT Resizing: {args.pot_size}x{args.pot_size} with WebP & PNG export")
        print(f"  - Three.js Material Code: {code_file.name}")
        print(f"  - Manifest: {manifest_file.name}\n")

    elif args.action == "code":
        three_code = generate_threejs_code(inspected)
        print("\n" + three_code)


if __name__ == "__main__":
    main()
